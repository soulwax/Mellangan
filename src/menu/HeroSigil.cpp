void heroSigil(Screen &s, int hero, float x, float y, float r, Color c, float t) {
  float cell = std::max(1.0f, std::floor(r * 2 / 13));
  float x0 = std::floor(x - cell * 6.5f), y0 = std::floor(y - cell * 6.5f);
  gui::glyph(s, SIGILS[hero % 12], 13, x0, y0, cell, c, t, INK);
  if (hero != 3)
    return;
  Color light{lerpf(c.r, 1, INK.lift), lerpf(c.g, 1, INK.lift), lerpf(c.b, 1, INK.lift), c.a};
  for (int i = 0; i < 3; i++) {
    float b = fract(t * 0.6f + i * 0.33f);
    s.rect(x0 + (5 + i) * cell, y0 + (2 - b * 4) * cell, cell, cell,
           light.alpha(c.a * (1 - b)));
  }
}
